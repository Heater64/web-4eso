/**
 * Create and show modal
 * @param {Object} options - Modal options
 * @returns {HTMLElement} Modal element
 */
function showModal(options) {
    const { 
        title, 
        content, 
        footer,
        onClose,
        size = 'medium',
        closable = true
    } = options;
    
    // Create modal overlay
    const overlay = document.createElement('div');
    overlay.className = 'modal-overlay active';
    overlay.innerHTML = `
        <div class="modal modal-${size}">
            <div class="modal-header">
                <h3 class="modal-title">${title}</h3>
                ${closable ? `
                    <button class="modal-close">
                        ${getIcon('x', 20)}
                    </button>
                ` : ''}
            </div>
            <div class="modal-body">
                ${content}
            </div>
            ${footer ? `<div class="modal-footer">${footer}</div>` : ''}
        </div>
    `;
    
    document.body.appendChild(overlay);
    document.body.style.overflow = 'hidden';
    
    // Close handlers
    const closeModal = () => {
        overlay.classList.remove('active');
        setTimeout(() => {
            overlay.remove();
            document.body.style.overflow = '';
        }, 300);
        if (onClose) onClose();
    };
    
    if (closable) {
        overlay.querySelector('.modal-close').addEventListener('click', closeModal);
        overlay.addEventListener('click', (e) => {
            if (e.target === overlay) closeModal();
        });
    }
    
    return { overlay, close: closeModal };
}

/**
 * Show confirm modal
 * @param {string} message - Confirm message
 * @param {Function} onConfirm - Confirm callback
 * @param {Function} onCancel - Cancel callback
 */
function showConfirm(message, onConfirm, onCancel) {
    const modal = showModal({
        title: 'Confirmar accion',
        content: `<p style="color: var(--text-secondary);">${message}</p>`,
        footer: `
            <button class="btn btn-secondary" id="modal-cancel">Cancelar</button>
            <button class="btn btn-primary" id="modal-confirm">Confirmar</button>
        `
    });
    
    modal.overlay.querySelector('#modal-cancel').addEventListener('click', () => {
        modal.close();
        if (onCancel) onCancel();
    });
    
    modal.overlay.querySelector('#modal-confirm').addEventListener('click', () => {
        modal.close();
        if (onConfirm) onConfirm();
    });
}

