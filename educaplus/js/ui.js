/**
 * Create skeleton loader
 * @param {string} type - Skeleton type
 * @param {number} count - Number of items
 * @returns {string} HTML string
 */
function createSkeleton(type, count = 1) {
    let html = '';
    
    for (let i = 0; i < count; i++) {
        switch (type) {
            case 'card':
                html += `
                    <div class="card skeleton-card">
                        <div class="skeleton skeleton-title"></div>
                        <div class="skeleton skeleton-text"></div>
                        <div class="skeleton skeleton-text" style="width: 80%;"></div>
                    </div>
                `;
                break;
            case 'stat':
                html += `
                    <div class="stat-card">
                        <div class="stat-card-header">
                            <div class="skeleton" style="width: 48px; height: 48px; border-radius: var(--radius-lg);"></div>
                        </div>
                        <div class="skeleton" style="height: 32px; width: 60%; margin-bottom: 8px;"></div>
                        <div class="skeleton" style="height: 16px; width: 40%;"></div>
                    </div>
                `;
                break;
            case 'file':
                html += `
                    <div class="file-row">
                        <div class="skeleton" style="width: 40px; height: 40px; border-radius: var(--radius-lg);"></div>
                        <div style="flex: 1;">
                            <div class="skeleton skeleton-text" style="width: 60%;"></div>
                            <div class="skeleton" style="height: 12px; width: 30%; margin-top: 4px;"></div>
                        </div>
                    </div>
                `;
                break;
            case 'text':
                html += `<div class="skeleton skeleton-text"></div>`;
                break;
            default:
                html += `<div class="skeleton" style="height: 40px;"></div>`;
        }
    }
    
    return html;
}

