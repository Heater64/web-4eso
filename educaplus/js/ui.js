/**
 * Get icon by name
 * @param {string} name - Icon name
 * @param {number} size - Icon size (default: 24)
 * @returns {string} SVG icon string
 */
function getIcon(name, size = 24) {
    const icon = Icons[name];
    if (!icon) return Icons.file;
    
    if (size !== 24) {
        return icon.replace(/width="24" height="24"/g, `width="${size}" height="${size}"`);
    }
    return icon;
}

